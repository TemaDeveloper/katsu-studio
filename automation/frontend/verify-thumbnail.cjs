// Targeted real-Chrome verification. Only the explicitly synthetic episode is changed.
const {chromium}=require(process.env.KATSU_PLAYWRIGHT_PATH || 'playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
 const out=path.resolve(__dirname,'../evidence'),base='http://127.0.0.1:8850';
 const fixture=JSON.parse(fs.readFileSync(path.join(out,'thumbnail-browser-fixture.json')));
 const original='17fce008-fe52-4864-8b09-1b595e32c235';
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1360,height:960}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${base}/projects/${original}`);
 await page.getByRole('heading',{name:'Why Are Humans Never Satisfied?'}).waitFor();
 await page.locator('video').evaluate(async v=>{v.muted=true;await v.play()});
 await page.waitForFunction(()=>document.querySelector('video').currentTime>0.1);
 await page.locator('video').evaluate(v=>v.pause());
 await page.getByRole('tab',{name:'Thumbnail',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.thumbnail-preview')?.naturalWidth===3840);
 assert((await page.locator('.thumbnail-headline').textContent()).includes('NEVER ENOUGH?'));
 assert((await page.locator('.thumbnail-details').textContent()).includes('artwork created in our session'));
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'Download thumbnail',exact:true}).click()]);
 assert.equal(await download.failure(),null);
 const saved=path.join(out,'first-thumbnail-downloaded.jpg');await download.saveAs(saved);
 assert.equal(fs.statSync(saved).size,440438);
 await page.screenshot({path:path.join(out,'thumbnail-desktop.png'),fullPage:true});
 assert(!(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)));
 await page.getByRole('tab',{name:'Thumbnail',exact:true}).focus();await page.keyboard.press('End');
 assert.equal(await page.getByRole('tab',{name:'Sources'}).getAttribute('aria-selected'),'true');
 await page.keyboard.press('Home');assert.equal(await page.getByRole('tab',{name:'Video',exact:true}).getAttribute('aria-selected'),'true');
 await page.getByRole('tab',{name:'Thumbnail',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'thumbnail-mobile.png'),fullPage:true});
 assert(!(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)));
 await page.goto(base);await page.getByRole('heading',{name:/My videos/}).waitFor();
 const cover=page.locator(`a[href="/projects/${original}"] img`);
 await cover.waitFor();assert((await cover.getAttribute('src')).includes('/artifacts/thumbnail'));
 await page.goto(`${base}/projects/${fixture.id}`);await page.getByRole('tab',{name:'Thumbnail',exact:true}).click();
 await page.getByRole('button',{name:'New thumbnail',exact:true}).click();
 await page.getByText('Add your OpenAI API key in Settings, then continue thumbnail production. Your video is saved.').waitFor();
 await page.getByRole('button',{name:'Continue production',exact:false}).waitFor();
 const p=await page.request.get(`${base}/api/projects/${fixture.id}`).then(r=>r.json());
 assert.equal(p.status,'needs_attention');assert.equal(p.stage,'thumbnail');assert.equal(p.thumbnail_only,true);
 assert.equal(p.artifacts.video.fingerprint,fixture.video);assert.equal(p.artifacts.audio.fingerprint,fixture.audio);
 assert.equal(p.estimated_committed_usd,fixture.estimated);assert(!p.artifacts.thumbnail);
 const requests=await page.request.get(`${base}/api/projects/${fixture.id}/requests`).then(r=>r.json());
 assert.equal(requests.length,fixture.requests);
 await page.getByRole('tab',{name:'Video',exact:true}).click();await page.locator('video').waitFor();
 await page.screenshot({path:path.join(out,'thumbnail-recovery-mobile.png'),fullPage:true});
 assert(!(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)));
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(out,'thumbnail-browser-verification.json'),JSON.stringify({passed:true,original,syntheticRecoveryProject:fixture.id,desktop:[1360,960],mobile:[390,844],previewDimensions:[3840,2160],downloadBytes:440438,videoPlayback:true,episodeCover:true,keyboardTabs:true,missingKeyRecovery:true,preservedVideo:true,preservedAudio:true,noAdditionalReservations:true,overflow:false,pageErrors:errors},null,2));
 console.log('Thumbnail browser verification passed: preview, download, cover, playback, five keyboard tabs, mobile, and recovery preserving video/audio without spending.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
